def run_tg_channel(username: str, channel_name: str,
                   posted_links: set, posted_titles: set, posted_keywords: list,
                   strict_fallback: bool = False, resolve_deeper: bool = False) -> None:
    from datetime import datetime, timezone, timedelta
    url = f"https://t.me/s/{username}"
    try:
        resp = requests.get(url, timeout=60, headers={
            "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) "
                          "AppleWebKit/537.36 Chrome/120.0.0.0 Safari/537.36"})
        resp.raise_for_status()
    except Exception as e:
        print(f"[@{username}] Не вдалось завантажити: {e}")
        return

    soup = BeautifulSoup(resp.text, "html.parser")
    messages = soup.find_all("div", class_="tgme_widget_message_wrap")
    if not messages:
        print(f"[@{username}] Повідомлень не знайдено")
        return

    print(f"[@{username}] Знайдено {len(messages)} повідомлень")
    cutoff = datetime.now(timezone.utc) - timedelta(days=7)

    for msg in reversed(messages):
        msg_link_tag = msg.find("a", class_="tgme_widget_message_date")
        if not msg_link_tag:
            continue
        msg_url = msg_link_tag.get("href", "")
        if not msg_url:
            continue

        item_key = f"tg_{username}_{msg_url.split('/')[-1]}"
        if item_key in posted_links:
            continue

        time_tag = msg_link_tag.find("time")
        if time_tag and time_tag.get("datetime"):
            try:
                msg_dt = datetime.fromisoformat(
                    time_tag["datetime"].replace("Z", "+00:00"))
                if msg_dt < cutoff:
                    save_posted_link(item_key)
                    posted_links.add(item_key)
                    continue
            except ValueError:
                pass

        text_div = msg.find("div", class_="tgme_widget_message_text")
        if not text_div:
            save_posted_link(item_key)
            posted_links.add(item_key)
            continue

        # "\n" як роздільник (а не " ") — зберігає структуру абзаців/
        # буліт-пунктів поста. З " " увесь текст склеювався в суцільне
        # полотно без жодного переносу рядка — це й було причиною
        # "простирадла" при сирій публікації (коли AI недоступний і
        # використовується raw_text як є), а заразом ламало first_line
        # нижче (text.split("\n")[0] завжди повертав увесь текст,
        # бо "\n" у ньому просто не було).
        text = text_div.get_text("\n", strip=True)
        # Рядки без жодної літери/цифри (лише емодзі-розділювачі "🌻", "🌍",
        # порожні дужки "( )") — це декор оригінального поста, а не зміст.
        # Без їх відсіву при сирій публікації (збій AI) пост виглядав як
        # стовпчик самих емодзі, а first_line (=заголовок) міг стати "🌍".
        # Абзаци склеюємо порожнім рядком, щоб структура лишалась читною.
        text = "\n\n".join(l.strip() for l in text.split("\n") if re.search(r"\w", l))
        if len(text) < 30:
            save_posted_link(item_key)
            posted_links.add(item_key)
            continue

        if is_tg_junk(text):
            print(f"[@{username}] Skipped (реклама/тендер): {text[:60]}")
            save_posted_link(item_key)
            posted_links.add(item_key)
            continue

        first_line = text.split("\n")[0].strip() or text[:200]

        print(f"[@{username}] Processing: {first_line[:60]}")
        deadline = extract_deadline(text)

        # TG-канал сам не є першоджерелом — він лише репостить. Шукаємо
        # реальне посилання прямо в тексті поста (Telegram сам робить URL
        # клікабельними, тож усі лінки вже є в text_div).
        source_url, source_label = find_original_source_link(text_div)

        # Для каналів-акселераторів (resolve_deeper=True) знайдений лінк —
        # це, найімовірніше, сторінка самого акселератора/посередника
        # (чи university international office), а НЕ сайт донора. Заходимо
        # на цю сторінку і шукаємо справжнє першоджерело ще на один рівень
        # глибше — так само, як для fundsforngos/GrantHub. Якщо глибший
        # лінк не знайдено — лишаємо те, що вже є (краще так, ніж нічого).
        if resolve_deeper and source_url and not is_social_media_url(source_url):
            try:
                own_domain = urlparse(source_url).netloc.lower().replace("www.", "")
                deeper_page = fetch_html(source_url, timeout=30, retries=1)
                if deeper_page:
                    deeper_url, deeper_label = find_original_source_link(
                        deeper_page, extra_skip_domains=(own_domain,))
                    if deeper_url:
                        source_url, source_label = deeper_url, deeper_label
            except Exception as e:
                print(f"[@{username}] Глибший пошук джерела не вдався: {e}")

        if not source_url:
            source_url, source_label = msg_url, f"{channel_name} — джерело"

        if is_cross_channel_digest_repost(text, source_url):
            # Чужий "грантовий дайджест" з посиланням на папку Google
            # Drive замість сторінки конкретного гранту — бот не вміє
            # надійно розкрити таку папку на окремі пункти, а публікація
            # одним розмитим постом із посиланням на чужу підбірку лише
            # засмічує канал. Пропускаємо одразу, без виклику AI.
            print(f"[@{username}] Skipped (чужий дайджест-репост, не конкретний грант): {first_line[:60]}")
            save_posted_link(item_key)
            posted_links.add(item_key)
            continue

        try:
            response = build_and_send("📌", first_line, source_url, text,
                                       source_label,
                                       posted_titles, posted_keywords, posted_links,
                                       deadline_hint=deadline, strict_fallback=strict_fallback)
            if response.status_code == 200:
                save_posted_link(item_key)
                posted_links.add(item_key)
            time.sleep(2)
        except Exception as e:
            print(f"[@{username}] ERROR {item_key}: {e}")


