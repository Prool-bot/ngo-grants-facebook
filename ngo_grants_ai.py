_TITLE_COUNTRY_RE = re.compile(
    r"(?<![A-Za-z])(?:" + "|".join(re.escape(w) for w in _TITLE_COUNTRY_WORDS) + r")(?![A-Za-z])")
_TITLE_GLOBAL_RE = re.compile(r"Ukrain|Global|Worldwide", re.I)


def is_title_country_restricted(title: str) -> bool:
    if _TITLE_GLOBAL_RE.search(title):
        return False
    return bool(_TITLE_COUNTRY_RE.search(title))


def is_likely_country_restricted(text: str) -> bool:
    # Якщо Україна згадана в тексті — це не "лише для однієї країни, що
    # виключає Україну" ("citizens of Ukraine only" тощо): не відсікаємо,
    # рішення лишається за AI.
    if re.search(r"\bUkrain|Україн", text, re.IGNORECASE):
        return False
    return any(re.search(p, text, re.IGNORECASE) for p in COUNTRY_RESTRICTED_PATTERNS)


def _squeeze(s: str) -> str:
    return re.sub(r"[^\w]+", "", s.lower())


_CHANNEL_PROMO_RE = re.compile(
    r"(t\.me/|telegram|телеграм|на\s+(?:нашому\s+)?каналі|в\s+(?:нашому\s+)?каналі|"
    r"підписуйт|підписатис|підписатись|більше\s+(?:грантів|можливостей))",
    re.I)


def _strip_channel_promo(text):
    """Прибирає рядки/речення-рекламу ІНШИХ каналів, що AI переніс з
    оригінального TG-поста ("Більше можливостей — на Telegram-каналі
    «Грантові фішки»"). Для нашого каналу це чужа реклама, не зміст."""
    if not text or not isinstance(text, str):
        return text
    parts = re.split(r"(?<=[.!?»])\s+|\n+", text)
    kept = [x for x in parts if x.strip() and not _CHANNEL_PROMO_RE.search(x)]
    return "\n".join(kept).strip() if len(kept) != len([x for x in parts if x.strip()]) else text


def _is_redundant_deadline_item(item: str, deadline: str) -> bool:
    """AI-інструкція прямо каже не повторювати дедлайн поза полем deadline,
    але модель (особливо Groq) це іноді ігнорує — кладе в
    application_requirements/notes пункт типу "Подати заявку до 1 вересня
    2026 12:00 CEST", що просто дублює вже показаний 📅 Дедлайн. Таке не
    ловить _dedupe_paragraphs (різні обгортки-заголовки навколо спільної
    дати не дають ≥60% збігу всього абзацу), тож перевіряємо прицільно:
    якщо сам рядок дедлайну (без пробілів/пунктуації) міститься всередині
    пункту — це майже напевно повторення, а не окрема вимога."""
    if not deadline:
        return False
    squeezed_deadline = _squeeze(deadline)
    return bool(squeezed_deadline) and squeezed_deadline in _squeeze(item)


def build_and_send(emoji: str, title: str, link: str, description: str,
                    source_label: str, posted_titles: set, posted_keywords: list,
                    posted_links: set, deadline_hint: str = "", strict_fallback: bool = False) -> requests.Response:
    """Єдина точка виходу: AI-розбір на секції → фільтр релевантності →
    stage-2 дедуп на нормалізованому заголовку → збірка HTML-повідомлення →
    надсилання. Довгі секції (notes, критерії, вимоги) відкидаються першими,
    якщо повідомлення не влазить у ліміт Telegram (4096 симв.).
    strict_fallback=True — для шумних джерел (Google Alerts): якщо AI
    впаде, пост НЕ публікується (замість публікації сирого тексту).

    posted_links перевіряється ТУТ, а не лише в кожного виклику окремо,
    бо на момент виклику `link` — це вже РЕЗОЛЬВЛЕНЕ першоджерело (після
    find_original_source_link у викликача), а не сира адреса з фіда.
    Різні агрегатори/канали часто цитують той самий грант з різними
    сирими URL, які лише ПІСЛЯ резолюції збігаються — рання перевірка
    на сирому лінку (в самому циклі джерела) цього не ловить, звідси й
    були повтори того самого гранту з кількох українських джерел."""
    if link in posted_links:
        print(f"[{source_label}] Skipped (дубль після резолюції першоджерела): {title[:60]}")
        return _SkippedIrrelevant()

    if is_ai_chat_share_url(link):
        print(f"[{source_label}] Skipped (посилання на ШІ-чат, не на першоджерело): {title[:60]}")
        return _SkippedIrrelevant()

    if strict_fallback and is_likely_country_restricted(f"{title} {description}"):
        print(f"[{source_label}] Skipped (схоже, обмежено конкретною країною — без виклику AI): {title[:60]}")
        return _SkippedIrrelevant()

    ai = reformat_post(f"{title}\n\n{description}", source_label, strict_fallback=strict_fallback)

    if not ai.get("is_relevant", True):
        reason = ("AI не відповів, ймовірно вичерпано денну квоту"
                  if ai.get("_ai_failed") else "не грант/захід за визначенням AI")
        print(f"[{source_label}] Skipped ({reason}): {title[:60]}")
        return _SkippedIrrelevant()

    if not ai.get("ukraine_eligible", True):
        print(f"[{source_label}] Skipped (не для України): {title[:60]}")
        return _SkippedIrrelevant()

    final_title = ai.get("title") or title
    deadline = ai.get("deadline") or deadline_hint

    # Запобіжник для шумних джерел (strict_fallback=True: Google Alerts,
    # AI-пошук) НА ВИПАДОК, якщо AI (Groq не завжди ідеально дотримується
    # інструкцій промпта) все одно позначив is_relevant=true для звичайної
    # новинної замітки "уряд/установа запустили програму" без жодних
    # даних для реальної подачі заявки (приклад: новина про грант штату
    # Одіша в Індії — ні дедлайну, ні суми, ні форми подачі, лише загальний
    # опис). Якщо немає ОДНОЧАСНО дедлайну, суми фінансування і додаткових
    # посилань (форма/деталі) — найімовірніше, це не оголошення прийому
    # заявок, а журналістське висвітлення. Не застосовуємо до довірених
    # 9 прямих джерел (strict_fallback=False) — там і так кожен запис уже
    # підтверджений грант із довіреного сайту.
    if strict_fallback and not deadline and not ai.get("funding") and not ai.get("extra_links"):
        print(f"[{source_label}] Skipped (новинна замітка без дедлайну/суми/форми подачі, а не оголошення гранту): {final_title[:60]}")
        return _SkippedIrrelevant()

    # Перевірка на прострочений дедлайн раніше стояла лише в 5 окремих
    # джерелах (ISAR/МФВ/УКФ/ВФ/УМФ), і там звіряла regex-дедлайн зі
    # сторінки ДО AI. Дедлайн, який повертає сам AI (ai.get("deadline")),
    # і TG-канали взагалі не перевірялись — звідси пропуск явно
    # застарілого гранту (наприклад "1 вересня 2020", коли зараз 2026).
    # Перевіряємо тут, централізовано, для ВСІХ джерел одразу.
    if deadline and is_deadline_passed(deadline):
        print(f"[{source_label}] Skipped (дедлайн уже минув): {final_title[:60]} — {deadline}")
        return _SkippedIrrelevant()

    ai_emoji = ai.get("emoji")
    final_emoji = ai_emoji if ai_emoji and len(ai_emoji) <= 4 else emoji

    # Stage 2: дедуп на AI-нормалізованому заголовку — спільний пул для
    # всіх джерел, ловить той самий грант із різних сайтів/каналів,
    # навіть якщо їхні сирі заголовки сформульовані по-різному.
    if is_title_duplicate(final_title, posted_titles) or is_semantic_duplicate(final_title, posted_keywords):
        print(f"[{source_label}] Skipped (дубль після AI-нормалізації): {final_title[:60]}")
        return _SkippedDuplicate()

    header = f"{final_emoji} <b>{final_title}</b>"

    meta = []
    if deadline:
        meta.append(f"📅 <b>Дедлайн:</b> {deadline}")
    if ai.get("geography"):
        meta.append(f"🌍 <b>Географія:</b> {ai['geography']}")
    meta_text = "\n".join(meta) if meta else None

    # (пріоритет, текст секції) — пріоритет 1 = найважливіше, викидається останнім
    sections = []
    ai["intro"] = _strip_channel_promo(ai.get("intro"))
    ai["notes"] = _strip_channel_promo(ai.get("notes"))
    if ai.get("intro"):
        sections.append((1, ai["intro"]))
    if meta_text:
        sections.append((1, meta_text))
    if ai.get("funding"):
        sections.append((2, "💰 <b>Фінансування:</b>\n" + _bullets(ai["funding"])))
    if ai.get("application_fee"):
        sections.append((2, f"💵 <b>Вступний внесок:</b> {ai['application_fee']}"))
    if ai.get("audience"):
        block = "👥 <b>Хто може податися:</b>\n" + _bullets(ai["audience"])
        if ai.get("audience_excluded"):
            block += f"\n{ai['audience_excluded']}"
        sections.append((2, block))
    if ai.get("ukraine_relevance"):
        sections.append((2, f"🇺🇦 {ai['ukraine_relevance']}"))
    if ai.get("eligible_categories"):
        sections.append((3, "🎨 <b>Допустимі напрями:</b>\n" + _bullets(ai["eligible_categories"])))
    if ai.get("supported"):
        sections.append((3, "💡 <b>Що підтримується:</b>\n" + _bullets(ai["supported"])))
    if ai.get("decision_date"):
        sections.append((3, f"📆 <b>Рішення про фінансування:</b> {ai['decision_date']}"))
    if ai.get("duration"):
        sections.append((3, f"⏳ <b>Тривалість:</b> {ai['duration']}"))
    if ai.get("evaluation_criteria"):
        sections.append((4, "🔬 <b>Оцінюватимуть:</b>\n" + _bullets(ai["evaluation_criteria"])))
    requirements = [r for r in (ai.get("application_requirements") or [])
                     if not _is_redundant_deadline_item(r, deadline)]
    if requirements:
        sections.append((4, "📝 <b>У заявці потрібно надати:</b>\n" + _bullets(requirements)))
    notes = ai.get("notes")
    if notes and not _is_redundant_deadline_item(notes, deadline):
        sections.append((5, notes))

    total_content_len = sum(len(text) for _, text in sections)
    # Дедлайн/географія — метадані, не ЗМІСТ. Пост типу "Дедлайн: 17
    # липня" без жодного реального опису (intro/funding/audience тощо)
    # проходив повз перевірку нижче, якщо сам рядок дедлайну випадково
    # набирав ≥60 символів — хоча по суті це той самий "порожній
    # контент", що й зовсім без секцій. Рахуємо змістовність ОКРЕМО від
    # meta, щоб meta-блок сам по собі не міг "витягнути" порожній пост.
    substantive_len = sum(len(text) for _, text in sections if text != meta_text)
    if not sections or total_content_len < 60 or substantive_len < 40:
        # Жодної секції (чи сукупно менше 60 символів, чи лишилась лише
        # мета-інформація без реального змісту) — ні intro (навіть
        # fallback на сирий текст порожній чи символічний), ні жодного
        # іншого поля. Найімовірніша причина: сайт-джерело віддає майже
        # порожній HTML без виконання JavaScript (сучасні сайти на React/
        # Webflow тощо) чи дату показує окремим віджетом-іконкою, а не
        # текстом — скрапер фізично не побачив реального тексту сторінки.
        # Публікація голого заголовка з посиланням без жодного змісту
        # гірша за пропуск, АЛЕ там може бути щось цінне (як і з
        # нерозпізнаними Instagram/Facebook постами) — тож не викидаємо
        # мовчки, а збираємо для email-дайджесту наприкінці прогону.
        global _empty_content_items
        _empty_content_items.append((title, link))
        print(f"[{source_label}] Skipped (порожній контент, надіслано на email): {title[:60]}")
        return _SkippedIrrelevant()

    main_link_label = ai.get("source_link_label") or source_label
    links_block = f"🔗 <a href=\"{link}\">{main_link_label}</a>"
    for l in (ai.get("extra_links") or []):
        url, label = l.get("url"), l.get("label")
        if url and label:
            links_block += f"\n🔗 <a href=\"{url}\">{label}</a>"

    body_for_hashtags = " ".join(
        [ai.get("intro") or "", ai.get("ukraine_relevance") or ""]
        + (ai.get("funding") or []) + (ai.get("supported") or [])
    )
    hashtags = generate_hashtags(final_title, body_for_hashtags)
    if "#Україна" not in hashtags and "#україна" not in hashtags.lower():
        hashtags = (hashtags + " #Україна").strip()

    # Конкретні AI-хештеги — окремий шар ПОВЕРХ системи фільтрів каналу
    # (яка лишається незмінною, бо задокументована для підписників у
    # закріпленому пості). Санітизуємо: лише буквено-цифрові символи,
    # без пробілів, не дублюємо вже наявні широкі категорії/#Україна,
    # максимум 5 штук про запас (AI просили 2-5, але подвір'я не зайве).
    existing_lower = hashtags.lower()
    extra_tags = []
    for raw in (ai.get("extra_hashtags") or [])[:5]:
        clean = re.sub(r"[^\w]", "", str(raw), flags=re.UNICODE)
        if clean and f"#{clean.lower()}" not in existing_lower:
            extra_tags.append(f"#{clean}")
    if extra_tags:
        hashtags = (hashtags + " " + " ".join(extra_tags)).strip()

    reserved = len(header) + len(links_block) + (len(hashtags) + 4 if hashtags else 0) + 20
    budget = 4000 - reserved  # запас нижче ліміту Telegram у 4096

    kept, used = [], 0
    for _, text in sorted(sections, key=lambda s: s[0]):
        if used + len(text) + 2 <= budget:
            kept.append(text)
            used += len(text) + 2

    parts = [header] + kept + [links_block]
    if hashtags:
        parts.append(hashtags)
    msg = _dedupe_paragraphs("\n\n".join(parts))

    # Пряме посилання на файл (PDF/DOC/DOCX тощо) замість вебсторінки —
    # Telegram рендерить це як файлову картку "назва.pdf, 72.7 KB", яка
    # виглядає геть інакше за звичне прев'ю сторінки і виламується з
    # усталеного вигляду каналу. Вимикаємо прев'ю саме для таких постів.
    is_file_link = link.split("?")[0].lower().endswith(
        (".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx"))

    resp = send_telegram_message(msg, disable_preview=is_file_link)
    print(resp.text)
    if resp.status_code == 200:
        save_title_hash(final_title, posted_titles, posted_keywords)
    return resp


