# Текст посилань, які ТЕЖ часто містять слово з PRIORITY_LINK_PATTERNS
# (наприклад "visit" у "visit our contact form", "website" у "subscribe
# on our website") але насправді ведуть не на сторінку гранту, а на
# форму зв'язку/контакти, підписку чи сторінку "про нас". Причина
# конкретного багу: допис про грант ACC (nac.foundation) отримав
# посиланням форму зворотного зв'язку замість https://www.nac.foundation/grants —
# бо анкор-текст форми теж містив "website"/"visit". Такі посилання
# пропускаємо навіть якщо вони відповідають PRIORITY_LINK_PATTERNS.
NEGATIVE_LINK_PATTERNS = re.compile(
    r"contact|feedback|subscribe|newsletter|donate|donation|privacy|"
    r"terms|about us|sign ?up|log ?in|контакт|зворотн|зв'язк|підписк|"
    r"пожертв|про нас|конфіденційн",
    re.I)


def find_original_source_link(page, extra_skip_domains: tuple = (), priority_only: bool = False) -> tuple:
    """Шукає на вже завантаженій сторінці (fundsforngos.org, opportunitiesradar.com
    тощо) посилання на справжнє першоджерело (сайт донора/фонду) — саме
    так, як це робиться вручну: заходимо на сторінку конкретної можливості
    й дивимось, куди вона веде далі. Ігнорує посилання на сам сайт-джерело
    (fundsforngos + будь-що з extra_skip_domains) і на соцмережі/ШІ-чати.
    Повертає (url, назва_джерела) або (None, None), якщо не знайдено."""
    skip_own = ("fundsforngos",) + extra_skip_domains

    # Власний домен сторінки — з <link rel="canonical"> чи <meta og:url>,
    # якщо є. Без цього fallback на всю сторінку (нижче) міг би підхопити
    # звичайне навігаційне посилання "На головну" й підмінити конкретну
    # статтю просто на домашню сторінку того ж сайту — це не першоджерело,
    # а крок НАЗАД у якості порівняно з уже наявною адресою статті.
    canonical = page.find("link", rel="canonical") or page.find("meta", property="og:url")
    self_url = (canonical.get("href") or canonical.get("content")) if canonical else None
    if self_url:
        self_domain = urlparse(self_url).netloc.lower().replace("www.", "")
        if self_domain:
            skip_own = skip_own + (self_domain,)

    def _resolve(href):
        """Якщо обраний кандидат — скорочувач (bit.ly тощо), розкриває
        його до справжньої адреси й перевіряє skip-правила ще раз (бо
        справжній домен стає відомим лише ПІСЛЯ розкриття). Повертає
        (href, label) або (None, None), якщо після розкриття посилання
        виявилось на себе ж / соцмережу."""
        resolved = expand_shortlink(href)
        netloc = urlparse(resolved).netloc.lower()
        if (not netloc or any(d in netloc for d in skip_own) or is_social_media_url(resolved)
                or is_ai_chat_share_url(resolved) or is_junk_source_url(resolved)):
            return None, None
        return resolved, netloc.replace("www.", "") + " — джерело"

    def _scan(scope):
        for a in scope.find_all("a", href=True):
            href = a["href"]
            netloc = urlparse(href).netloc.lower()
            path = urlparse(href).path.lower()
            if (not netloc or any(d in netloc for d in skip_own) or is_social_media_url(href)
                    or is_ai_chat_share_url(href) or is_junk_source_url(href)):
                continue
            if path.endswith((".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg")):
                # Пряме посилання на файл картинки — майже завжди це
                # обгортка навколо featured-зображення статті (клік
                # відкриває фото в повний розмір), а не справжнє джерело.
                continue
            resolved_href, resolved_label = _resolve(href)
            if not resolved_href:
                continue
            return resolved_href, resolved_label
        return None, None

    # Текст посилання, що майже напевно веде на справжнє першоджерело
    # (кнопка "Apply Now", рядок "For more information, visit..." тощо).
    # Раніше бралося просто ПЕРШЕ зовнішнє посилання на сторінці — на
    # агрегаторах типу fundsforngos це часто виявлявся сторонній сервіс
    # чи партнерський банер десь угорі, а справжнє посилання на донора
    # лежить нижче, у кінці статті. Тому спершу шукаємо "промовисті"
    # (PRIORITY_LINK_PATTERNS — на рівні модуля, вище).
    def _scan_priority(scope):
        # Збираємо ВСІ підходящі кандидати, а не перший-ліпший: на
        # сторінці часто є і "правильне" посилання на саму сторінку
        # гранту (напр. /grants), і сусіднє посилання з таким самим
        # "промовистим" словом у анкорі, що веде на форму зв'язку чи
        # головну сторінку сайту. Серед кандидатів беремо той, чий шлях
        # НЕ є порожнім/кореневим ("/") — бо гола адреса домену майже
        # завжди означає "головна сторінка", а не конкретна сторінка
        # гранту, навіть якщо текст посилання формально підійшов.
        candidates = []
        for a in scope.find_all("a", href=True):
            href = a["href"]
            anchor_text = a.get_text(" ", strip=True)
            if not anchor_text or not PRIORITY_LINK_PATTERNS.search(anchor_text):
                continue
            if NEGATIVE_LINK_PATTERNS.search(anchor_text):
                continue
            netloc = urlparse(href).netloc.lower()
            path = urlparse(href).path.lower()
            if (not netloc or any(d in netloc for d in skip_own) or is_social_media_url(href)
                    or is_ai_chat_share_url(href) or is_junk_source_url(href)):
                continue
            if path.endswith((".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg")):
                continue
            candidates.append((href, path.strip("/")))
        if not candidates:
            return None, None
        candidates.sort(key=lambda c: c[1] == "")
        for href, _path in candidates:
            resolved_href, resolved_label = _resolve(href)
            if resolved_href:
                return resolved_href, resolved_label
        return None, None

    content = page.find("div", class_=re.compile(r"entry-content|post-content|content", re.I))
    for scope in ([content] if content else []) + [page]:
        found = _scan_priority(scope)
        if found[0]:
            return found

    if priority_only:
        # Лише "промовисті" посилання (Apply/Official/Visit...). Жодного
        # "перше зовнішнє посилання на сторінці": для сторінки, що може
        # САМА бути першоджерелом, воно майже завжди з футера/сайдбара.
        return None, None

    if content:
        found = _scan(content)
        if found[0]:
            return found
        # Регулярний вираз "content" надто широкий — часто ловить дрібну
        # обгортку типу кнопок "Поділитись" (class="share-content") замість
        # справжнього тіла статті, і пошук у ній вичерпується без
        # результату. Не здаємось — пробуємо ще раз по ВСІЙ сторінці,
        # перш ніж визнати, що посилання на першоджерело справді немає.
    return _scan(page)


# Заголовки-пункти, які насправді є шаблонною навігацією/сайдбаром, а не
# назвою окремої можливості — "How to Apply", "News & updates", "Visit"
# тощо. Перша реальна перевірка (на живому прогоні) показала, що звичайні
# одиничні статті (новина про один грант, шкільний календар, сторінка
# держустанови) майже завжди мають 2-5 таких побічних посилань у
# навігації/сайдбарі/футері — без цього фільтра вони хибно розпізнавались
# як "дайджест" із кількома можливостями.
_GENERIC_LISTING_HEADINGS = {
    "visit", "apply", "more", "details", "website", "subscribe",
    "learn more", "read more", "how to apply", "news", "updates",
    "news & updates", "news and updates", "contact", "contact us",
    "visit campus", "visit website", "official website", "apply now",
    "подати заявку", "детальніше", "докладніше", "джерело",
}


def extract_listing_items(page, skip_domains: tuple = ()) -> list:
    """Виявляє, чи сторінка (куди привів Google Alert чи інший агрегатор)
    САМА Є дайджестом кількох РІЗНИХ можливостей (як щомісячні збірки
    Impact Funding тощо), а не однією конкретною статтею — і якщо так,
    розбиває на окремі пункти (назва, короткий опис, посилання).

    Навмисно КОНСЕРВАТИВНО (перша версія хибно ловила звичайні одиничні
    статті через побічні nav/сайдбар-посилання, що теж матчились на
    "apply"/"visit"/"more" тощо):
    - шукає лише в основному контент-блоці статті (entry-content/post-
      content/content) — НЕ в усій сторінці, де сидять nav/сайдбар/футер;
      якщо такого блоку не знайдено, вважає, що це НЕ дайджест (повертає
      [] — сторінка обробляється як одна можливість, як і раніше);
    - вимагає, щоб заголовок пункту був змістовним (≥15 символів) і НЕ
      зі списку шаблонних фраз (_GENERIC_LISTING_HEADINGS);
    - дедуплікує за НОРМАЛІЗОВАНИМ заголовком, а не лише href (однакові
      сайдбар-блоки типу "News & updates" із різними href інакше й далі
      проходили б як "різні" пункти);
    - вимагає мінімум 3 РІЗНИХ таких пункти (не 2) — цей порядок величини
      відповідає реальним дайджестам (Impact Funding: "5 new
      opportunities"), а 2 випадкові CTA на одній статті (кнопка "Apply"
      нагорі + посилання "офіційний сайт" у кінці) — звичайна річ навіть
      для ОДНІЄЇ можливості."""
    content = page.find("div", class_=re.compile(r"entry-content|post-content|content", re.I))
    if not content:
        return []

    seen_hrefs = set()
    seen_headings = set()
    items = []
    for a in content.find_all("a", href=True):
        href = a["href"]
        text = a.get_text(" ", strip=True)
        if not text or not PRIORITY_LINK_PATTERNS.search(text):
            continue
        netloc = urlparse(href).netloc.lower()
        path = urlparse(href).path.lower()
        if not netloc or any(d in netloc for d in skip_domains) or is_social_media_url(href) or is_ai_chat_share_url(href):
            continue
        if path.endswith((".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg")):
            continue
        if href in seen_hrefs:
            continue

        heading = a.find_previous(["h1", "h2", "h3", "h4", "strong", "b"])
        title = heading.get_text(" ", strip=True) if heading else ""
        title_norm = title.strip().lower()
        if len(title) < 15 or title_norm in _GENERIC_LISTING_HEADINGS:
            continue
        if title_norm in seen_headings:
            continue

        container = a.find_parent(["li", "p", "div"]) or a.parent
        snippet = container.get_text(" ", strip=True) if container else text
        if len(snippet) < 100:
            continue

        seen_hrefs.add(href)
        seen_headings.add(title_norm)
        items.append((title.strip(), snippet.strip()[:1500], href))

    if len(items) < 3:
        return []
    return items


def process_fundsforngos_listing(digest_url: str, posted_links: set,
                                  posted_titles: set, posted_keywords: list,
                                  counter: dict) -> None:
    """fundsforngos.org/listing/... — щоденна збірка ~20-30 можливостей у
    форматі: жирний заголовок / Deadline: дата / опис / посилання 'more'.
    Розбираємо на окремі пункти; для кожного заходимо на його власну
    сторінку fundsforngos.org (як вручну), беремо звідти повний опис і
    шукаємо посилання на справжнє першоджерело — саме воно, а не сторінка
    fundsforngos.org, стає посиланням у фінальному пості. Рахуємо в
    спільний ліміт публікацій за прогін (counter), щоб не залити канал."""
    page = fetch_html(digest_url)
    if not page:
        print(f"[fundsforngos] Не вдалось завантажити збірку: {digest_url}")
        return

    items_found = 0
    for p in page.find_all("p"):
        if counter["count"] >= GOOGLE_ALERTS_MAX_PER_RUN:
            print(f"[fundsforngos] Досягнуто ліміт {GOOGLE_ALERTS_MAX_PER_RUN} публікацій за прогін — решта зачекає наступного запуску")
            break

        more_link = None
        for a in p.find_all("a"):
            if a.get_text(strip=True).lower() in ("more", "read more", "[more]", "more…", "more..."):
                more_link = a.get("href")
                break
        if not more_link:
            continue

        item_url = more_link.strip()
        if item_url in posted_links:
            continue

        full_text = p.get_text("\n", strip=True)
        lines = [l for l in full_text.split("\n") if l.strip()]
        if not lines:
            continue
        title = lines[0].strip()

        deadline_match = re.search(r"Deadline\s*:?\s*(.+)", full_text, re.IGNORECASE)
        deadline_hint = deadline_match.group(1).split("\n")[0].strip() if deadline_match else ""

        if is_excluded(title) or is_excluded(full_text) or is_title_country_restricted(title):
            save_posted_link(item_url)
            posted_links.add(item_url)
            continue

        # Заходимо на власну сторінку гранту на fundsforngos.org — там і
        # повніший опис, і посилання на першоджерело
        item_page = fetch_html(item_url)
        if item_page:
            description = collect_paragraphs(item_page, min_len=80) or full_text
            source_url, source_label = find_original_source_link(item_page)
        else:
            # Сторінку конкретного пункту не вдалось завантажити (403
            # тощо) — як і в run_fundsforngos_feed, не підписуємо
            # публікацію посиланням на (недоступну) сторінку
            # fundsforngos.org під виглядом першоджерела. Пробуємо
            # знайти зовнішнє посилання прямо в HTML збірки навколо
            # цього пункту (p), перш ніж здатися.
            description = full_text
            source_url, source_label = find_original_source_link(p)
        if not source_url:
            found_url, found_label, found_snippet = find_source_via_search(title)
            if found_url:
                print(f"[fundsforngos] Першоджерело знайдено пошуком: {found_url}")
                source_url, source_label = found_url, found_label
                src_page = fetch_html(found_url)
                description = (collect_paragraphs(src_page, min_len=80) if src_page else "") or found_snippet or description
        if not source_url:
            _unresolved_source_items.append((title, item_url))
            print(f"[fundsforngos] Skipped (першоджерело не знайдено, сторінка недоступна): {title[:60]}")
            save_posted_link(item_url)
            posted_links.add(item_url)
            continue

        items_found += 1
        try:
            resp = build_and_send("🌍", title, source_url, description,
                                   source_label,
                                   posted_titles, posted_keywords, posted_links,
                                   deadline_hint=deadline_hint, strict_fallback=True)
            if resp.status_code == 200:
                save_posted_link(item_url)
                posted_links.add(item_url)
                if not isinstance(resp, _SKIP_SENTINELS):
                    counter["count"] += 1
        except Exception as e:
            print(f"[fundsforngos] ERROR {item_url}: {e}")
        time.sleep(2)

    print(f"[fundsforngos] Розібрано нових пунктів зі збірки: {items_found}")


def run_google_alert(feed_url: str, alert_label: str, posted_links: set,
                      posted_titles: set, posted_keywords: list, counter: dict,
                      unresolved_social: list) -> None:
    feed = feedparser.parse(feed_url)
    if not feed.entries:
        print(f"[{alert_label}] Немає записів")
        return
    print(f"[{alert_label}] Знайдено {len(feed.entries)} записів")

    already_posted = 0
    filtered_out = 0
    new_processed = 0

    for entry in reversed(feed.entries):
        if counter["count"] >= GOOGLE_ALERTS_MAX_PER_RUN:
            print(f"[{alert_label}] Досягнуто ліміт {GOOGLE_ALERTS_MAX_PER_RUN} публікацій за прогін — решта зачекає наступного запуску")
            break

        raw_title = clean_html_description(getattr(entry, "title", "") or "")
        google_link = getattr(entry, "link", "")
        real_url = extract_real_url(google_link)
        if not real_url:
            continue

        if real_url in posted_links:
            already_posted += 1
            continue

        if is_excluded(raw_title):
            filtered_out += 1
            save_posted_link(real_url)
            posted_links.add(real_url)
            continue

        new_processed += 1
        if "fundsforngos.org/listing/" in real_url:
            process_fundsforngos_listing(real_url, posted_links, posted_titles, posted_keywords, counter)
            save_posted_link(real_url)
            posted_links.add(real_url)
            continue

        original_alert_url = real_url
        description = None
        if is_social_media_url(real_url):
            netloc_check = urlparse(real_url).netloc.lower()
            if "x.com" in netloc_check or "twitter.com" in netloc_check:
                tweet_text, tweet_link = fetch_tweet_content(real_url)
                if not tweet_text:
                    print(f"[{alert_label}] Skipped (твіт не вдалось прочитати): {raw_title[:60]}")
                    save_posted_link(real_url)
                    posted_links.add(real_url)
                    continue
                if not tweet_link:
                    # Раніше тут все одно публікувалось із самим твітом
                    # як джерелом ("x.com — джерело" чи AI-згенероване
                    # "Твіт про грант") — непослідовно з тим, як
                    # обробляються Facebook/Instagram нижче (там
                    # відсутність посилання всередині посту = пропуск +
                    # email). Твіт без вбудованого посилання так само не
                    # першоджерело, а лише згадка — вирівнюємо поведінку.
                    print(f"[{alert_label}] Skipped (твіт без посилання на першоджерело, надіслано на email): {raw_title[:60]}")
                    save_posted_link(real_url)
                    posted_links.add(real_url)
                    unresolved_social.append((raw_title, real_url))
                    continue
                description = tweet_text
                real_url = tweet_link
                tweet_page = fetch_html(real_url)
                fuller = collect_paragraphs(tweet_page, min_len=100) if tweet_page else ""
                if fuller:
                    description = fuller
                domain = urlparse(real_url).netloc.lower().replace("www.", "")
                netloc_source = f"{domain} — джерело" if domain else "x.com — джерело"
            else:
                # Facebook/Instagram — простий перехід. Instagram майже
                # завжди тут впаде (блокує датацентрові IP на першому ж
                # запиті) — це очікувано, обробляється як пропуск нижче.
                social_page = fetch_html(real_url)
                found_url, found_label = (find_original_source_link(social_page)
                                           if social_page else (None, None))
                if not found_url:
                    print(f"[{alert_label}] Skipped (лише соцмережа, першоджерело не знайдено, надіслано на email): {raw_title[:60]}")
                    save_posted_link(real_url)
                    posted_links.add(real_url)
                    unresolved_social.append((raw_title, real_url))
                    continue
                real_url, netloc_source = found_url, found_label
        else:
            # Універсальний пошук першоджерела для БУДЬ-ЯКОГО сайту, не
            # лише зі списку KNOWN_AGGREGATOR_DOMAINS. Раніше нові
            # агрегатори (типу opportunitiesforyouth.org) доводилось
            # виявляти вручну після того, як хибне посилання вже
            # опублікувалось, і щоразу дописувати домен у список.
            # Свідомий компроміс: іноді це може підмінити ПРАВИЛЬНЕ
            # посилання на справжньому першоджерелі випадковим вихідним
            # посиланням із тексту сторінки (банер партнера, related-
            # стаття тощо) — знайти й опублікувати першоджерело для
            # невідомого агрегатора важливіше за цей рідший ризик.
            agg_page = fetch_html(real_url)

            # СПОЧАТКУ перевіряємо, чи сторінка сама є ДАЙДЖЕСТОМ кількох
            # РІЗНИХ можливостей (як щомісячні збірки Impact Funding тощо),
            # а не однією конкретною. Якщо так — розбиваємо на окремі
            # пункти, для КОЖНОГО окремо шукаємо першоджерело ще на крок
            # глибше (той самий ланцюжок дайджест → агрегатор → донор, що
            # і для fundsforngos.org/listing/), і публікуємо кожен пункт
            # окремим постом — замість одного поста з назвою лише ПЕРШОЇ
            # можливості з усієї збірки, а текстом усієї сторінки.
            listing_items = extract_listing_items(agg_page, KNOWN_AGGREGATOR_DOMAINS) if agg_page else []
